#!/usr/bin/env python3
"""Turn db/seed.json into db/seed.sql (plain SQL: run it in psql or the Supabase SQL editor after db/schema.sql)."""
import json, uuid, re
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
s = json.loads((ROOT / "db/seed.json").read_text())

def q(v):
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

CAT = {"BIM Department Manager": "department_manager", "BIM Manager": "bim_manager", "BIM Coordinator": "bim_coordinator",
       "BIM Specialist": "bim_specialist", "R&D BIM Engineer": "rd_engineer"}
def flag(f):
    f = (f or "").strip().lower()
    return "Active" if f == "active" else "Not Active" if f == "not active" else ""
MAP = [("Open", "Active", "In Progress", "Open + Active"),
       ("Open", "Not Active", "Not Started", "ASSUMPTION: Open but flagged Not Active. Confirm with the department."),
       ("Open", "", "In Progress", "ASSUMPTION: Open with no activity flag. Confirm with the department."),
       ("Hold", "", "On Hold", None), ("Closed", "", "Closed", None),
       ("Terminated", "", "Closed", "ASSUMPTION: listed on Sheet2 but unused. Confirm.")]
def mapped(st, f):
    f = flag(f)
    for a, b, t, _ in MAP:
        if a == st and b == f: return t
    for a, b, t, _ in MAP:
        if a == st and b == "": return t
    return "Not Started"

out = ["-- Generated by scripts/build_seed_sql.py from the supplied org chart, workbook and Reel Plan. Run once on an empty database.", "begin;"]
E = {e["idx"]: str(uuid.uuid4()) for e in s["employees"]}
P = {p["idx"]: str(uuid.uuid4()) for p in s["projects"]}
for a, b, t, n in MAP:
    out.append(f"insert into status_mappings(source_status,activity_flag,target_status,note) values({q(a)},{q(b)},{q(t)},{q(n)});")
for e in s["employees"]:
    out.append("insert into employees(id,employee_code,name,job_title,job_category,discipline,year_value,team_location) values("
               f"{q(E[e['idx']])},{q(e['employee_id'])},{q(e['name'])},{q(e['job_title'])},{q(CAT[e['job_title']])},{q(e['discipline'])},{q(e['year'])},{q(e['team_location'])});")
for e in s["employees"]:
    if e["reports_to_idx"] is not None:
        out.append(f"insert into reporting_relationships(employee_id,manager_id) values({q(E[e['idx']])},{q(E[e['reports_to_idx']])});")
names = {e["name"]: e["idx"] for e in s["employees"]}
for alias, v in s["aliases"].items():
    out.append(f"insert into employee_aliases(employee_id,alias,reason) values({q(E[names[v['canonical']]])},{q(alias)},{q(v['reason'])});")
for p in s["projects"]:
    st = mapped(p["status_raw"], p["activity"])
    rows = "'{" + ",".join(map(str, p["source_rows"])) + "}'"
    out.append("insert into projects(id,project_no,name,cde,type,built_up_area,area_raw,area_note,status_raw,activity_raw,status,source_rows) values("
               f"{q(P[p['idx']])},{q(p['project_no'])},{q(p['name'])},{q(p['cde'])},{q(p['type'])},{q(p['area'])},{q(p['area_raw'])},{q(p['area_note'])},"
               f"{q(p['status_raw'])},{q(p['activity'])},{q(st)},{rows});")
    why = f"Initial import (workbook status \"{p['status_raw'] or ''}\"" + (f", flag \"{p['activity']}\"" if p["activity"] else "") + ")"
    out.append(f"insert into project_status_history(project_id,old_status,new_status,reason,changed_by) values({q(P[p['idx']])},null,{q(st)},{q(why)},'import');")
for a in s["assignments"]:
    out.append(f"insert into project_assignments(project_id,employee_id,role,source_row) values({q(P[a['project_idx']])},{q(E[a['employee_idx']])},{q(a['role'])},{q(a['source_row'])}) on conflict do nothing;")
for r in s["reels"]:
    emp = q(E[r["employee_idx"]]) if r["employee_idx"] is not None else "null"
    out.append(f"insert into reel_sessions(employee_id,presenter_code,presenter_name,weekday,session_date,topic) values({emp},{q(r['employee_id'])},{q(r['presenter_name'])},{q(r['weekday'])},{q(r['date'])},{q(r['topic'])});")
cap = {"max_projects_per_coordinator": None, "max_projects_per_manager": None, "max_area_per_coordinator": None, "max_area_per_manager": None,
       "hours_per_project": None, "available_hours_per_person": None, "imbalance_ratio": 1.5, "area_weight": 0, "count_statuses": ["In Progress", "Not Started"]}
out.append(f"insert into app_settings(key,value) values('capacity',{q(json.dumps(cap))}::jsonb),('alerts',{q(json.dumps({'reel_reminder_days': 7, 'outlier_area': 5000000}))}::jsonb);")
run = str(uuid.uuid4())
summ = {"employees": len(s["employees"]), "projects": len(s["projects"]), "assignments": len(s["assignments"]), "reels": len(s["reels"])}
out.append(f"insert into import_runs(id,source,run_by,summary) values({q(run)},'initial seed (xlsx + docx + reel image)','seed',{q(json.dumps(summ))}::jsonb);")
for i in s["issues"]:
    out.append(f"insert into data_issues(import_run,severity,kind,entity,message) values({q(run)},{q(i['severity'])},{q(i['kind'])},{q(i['entity'])},{q(i['message'])});")
out.append("commit;")
(ROOT / "db/seed.sql").write_text("\n".join(out) + "\n")
print(len(out), "statements")
